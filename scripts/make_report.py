def table(name, header, rows, spec):
    tx.append("\\newcommand{\\%s}{%%" % name)
    tx.append("\\begin{tabular}{%s}\\toprule" % spec)
    tx.append(" & ".join(header) + " \\\\ \\midrule")
    for r in rows:
        tx.append(" & ".join(str(x) for x in r) + " \\\\")
    tx.append("\\bottomrule\\end{tabular}}")


