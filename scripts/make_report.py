#!/usr/bin/env python3
"""Write docs/RESULTS.md and paper/generated.tex from one analysed run.

    python3 scripts/analyze.py results/raw/<run>
    python3 scripts/make_report.py <run>

Every number in both outputs is computed here from results/summary/<run>/*.csv and
results/raw/<run>/*.csv; nothing is typed by hand.
"""
import os
import shutil
import sys

import pandas as pd

run = sys.argv[1]
S = os.path.join("results", "summary", run)
R = os.path.join("results", "raw", run)
rd = lambda name: pd.read_csv(os.path.join(S, name))
raw = lambda name: pd.read_csv(os.path.join(R, name))

ovn, allb, bud = rd("compiler_old_vs_new.csv"), rd("compiler_strata_vs_all.csv"), rd("budget_min_buffer.csv")
rt, work = rd("compiler_replay_time.csv"), rd("compiler_workloads.csv")
cs, ss, ls = raw("compiler_summary.csv"), raw("synthetic_summary.csv"), raw("legacy_summary.csv")
sovn, srt = rd("synthetic_old_vs_new.csv"), rd("synthetic_replay_time.csv")
lovn = rd("legacy_old_vs_new.csv")
wc = raw("worstcase.csv")
env = open(os.path.join(R, "environment.txt")).read().strip()


def rng(series, fmt="%.1f"):
    return (fmt + " to " + fmt) % (series.min(), series.max())


def piv(df, value, cols, index="trace"):
    p = df.pivot(index=index, columns="impl", values=value)
    return p[[c for c in cols if c in p.columns]]


def verdict(series):
    """Plain statement of a reduction column: how many traces improved and the range."""
    better = int((series > 0).sum())
    word = "**Lower on every trace**" if better == len(series) else ("**Higher (worse) on every trace**" if better == 0 else "**Mixed**")
    return "%s: lower on %d of %d traces, reduction %s%%" % (word, better, len(series), rng(series))


def n_bad(df):
    return int(((df.wrong_lookups > 0) | (df.wrong_declares > 0) | (df.refused_declares > 0)).sum())


traces = list(work.trace)
heap = ovn["peak heap red. %"]
tim = ovn["replay red. %"]
alloc = ovn["allocs red. %"]
overlap = list(ovn[ovn["intervals overlap"] == "yes"].trace)
fx_m = bud["vs METIS-X (previous) peak heap, red. %"]
fx_s = bud["vs Swiss flat map, interned peak heap, red. %"]
sw = allb[allb.baseline == "Swiss flat map, interned"].iloc[0]
iqr = rt.iqr_pct_of_median
strata_ns = rt[rt.impl == "strata"].set_index("trace").ns_per_op
sparse_ns = rt[rt.impl == "strata_sparse"].set_index("trace").ns_per_op
raw_ns = rt[rt.impl == "strata_raw"].set_index("trace").ns_per_op
swiss_ns = rt[rt.impl == "swiss_interned"].set_index("trace").ns_per_op
sparse_gain = (strata_ns - sparse_ns) / strata_ns * 100
sparse_mem = (bud["min buffer KiB (sparse index)"] - bud["min buffer KiB (packed)"]) / bud["min buffer KiB (packed)"] * 100
pack_time = (raw_ns - strata_ns) / raw_ns * 100       # positive: packed is faster
slower_than_swiss = int((strata_ns > swiss_ns).sum())
ds = ss[(ss.trace == "deep_shadow_400") & (ss.impl == "metis_x")].iloc[0]
big = srt[srt.trace == "big_scope_exit"].set_index("impl").ns_per_op
met85_fixed = list(bud[fx_s >= 85].trace)

COLS = ["strata", "metis_x", "scope_map_stack", "std_undo_log", "swiss_undo_log", "swiss_interned"]
NAMES = {"strata": "STRATA", "metis_x": "METIS-X", "scope_map_stack": "map/scope", "std_undo_log": "std+undo",
         "swiss_undo_log": "Swiss+undo", "swiss_interned": "Swiss int.", "strata_sparse": "STRATA sparse",
         "strata_raw": "STRATA raw", "strata_noshrink": "STRATA no-shrink", "metis_arena_lp": "old arena",
         "metis_scope_maps": "old maps"}

# ------------------------------------------------------------------ RESULTS.md
md = []
A = md.append
A("# Results\n")
A("Run `%s`. Generated by `scripts/make_report.py`; every number is computed from "
  "`results/summary/%s/` and `results/raw/%s/`. Full tables: `results/summary/%s/tables.md`.\n" % (run, run, run, run))
A("```\n" + env + "\n```\n")
A("Reduction always means `(baseline - STRATA) / baseline x 100`. A negative reduction means STRATA is worse.\n")

A("## Summary\n")
A("| Hypothesis / target | Outcome |\n|---|---|")
A("| Correctness: agreement with the reference model | %d of %d compiler pairs, %d of %d synthetic pairs, %d of %d legacy pairs have no wrong or refused result. The only failures are METIS-X on `deep_shadow_400`. |"
  % (len(cs) - n_bad(cs), len(cs), len(ss) - n_bad(ss), len(ss), len(ls) - n_bad(ls), len(ls)))
A("| H1 memory: below every other table on compiler traces | **Holds on all %d traces.** Peak heap %s%% below METIS-X (median %.1f%%). |" % (len(traces), rng(heap), heap.median()))
A("| H2 time: replay not slower than METIS-X | **Holds on all %d traces** (%s%% lower, median %.1f%%); on %d of them (%s) the 95%% intervals overlap, so the difference is not established there. |"
  % (len(traces), rng(tim), tim.median(), len(overlap), ", ".join(overlap)))
A("| H3 fixed memory: whole trace from one buffer, no allocator | **Holds.** Minimum buffer %s KiB, %s bytes per live declaration. |"
  % (rng(bud["min buffer KiB (packed)"]), rng(bud["bytes per live decl"])))
A("| 85%% target, allocator calls vs METIS-X | **Met on all traces** (%s%%). |" % rng(alloc))
A("| 85%% target, memory vs METIS-X | **Not met.** Best case %.1f%% (peak heap) and %.1f%% (fixed buffer against METIS-X's peak heap). |" % (heap.max(), fx_m.max()))
A("| 85%% target, memory vs any baseline | Met only against the interning Swiss map, in fixed-buffer mode, on %d of %d traces (%s). |" % (len(met85_fixed), len(traces), ", ".join(met85_fixed)))
A("| 85% target, any latency or time metric | **Not met.** |")
A("| Lookup latency p95 vs METIS-X | %s. |" % verdict(ovn["lookup p95 red. %"]))
A("| Declare latency p95 vs METIS-X | %s. |" % verdict(ovn["declare p95 red. %"]))
A("| Scope-exit latency p95 vs METIS-X | %s. |" % verdict(ovn["exit p95 red. %"]))
A("| Speed vs the fastest baseline (`swiss_interned`) | STRATA is slower on %d of %d traces (replay time %s%%, median %.1f%%), with %s%% less peak heap. |"
  % (slower_than_swiss, len(traces), rng(pd.Series([sw["replay time red. % min"], sw["max "]])), sw["median "], rng(pd.Series([sw["peak heap red. % min"], sw["max"]]))))
A("")

A("## A. Compiler traces\n")
A("### Workloads\n")
A(work.to_markdown(index=False))
A("\nAt the peak, live declarations equal distinct live names on every trace except one (`tinycc`, by one): "
  "TCC-compiled C has almost no shadowing at the moment of peak memory, so storing a name once does not by itself save memory here.\n")
A("### Previous implementation versus STRATA\n")
A(ovn.round(1).to_markdown(index=False))
A("\nSources: `results/summary/%s/compiler_old_vs_new.csv`; raw: `compiler_summary.csv`, `compiler_replays.csv`; script: `benchmarks/bench_main.cpp`.\n" % run)
A("### Peak heap, KiB\n")
A((piv(cs, "peak_bytes", COLS) / 1024).round(1).rename(columns=NAMES).loc[traces].reset_index().to_markdown(index=False))
A("\n![memory](../results/summary/%s/fig_compiler_memory.png)\n" % run)
A("### Replay time, ns per trace operation (median of 15)\n")
A(piv(rt, "ns_per_op", COLS + ["strata_sparse", "strata_raw", "strata_noshrink"]).round(1).rename(columns=NAMES).loc[traces].reset_index().to_markdown(index=False))
A("\nInterquartile range of the 15 replays, as a percentage of the median: median %.1f%%, 90th percentile %.1f%%, maximum %.1f%% over the %d table/trace pairs. "
  "Per-pair 95%% bootstrap intervals are in `compiler_replay_time.csv`.\n" % (iqr.median(), iqr.quantile(0.9), iqr.max(), len(rt)))
A("![time](../results/summary/%s/fig_compiler_time.png)\n" % run)
A("### STRATA against every baseline\n")
A(allb.round(1).to_markdown(index=False))
A("")
for metric, title in (("lookup_p95_ns", "Lookup latency p95, ns"), ("declare_p95_ns", "Declare latency p95, ns"), ("exit_p95_ns", "Scope-exit latency p95, ns")):
    A("### %s\n" % title)
    A(piv(cs, metric, COLS + ["strata_sparse"]).round(0).rename(columns=NAMES).loc[traces].reset_index().to_markdown(index=False))
    A("")
A("Per-call values include a serialising timestamp read on each side; the calibrated cost of an empty interval (%.0f ns) is subtracted. "
  "p50 and p99 are in `compiler_summary.csv`.\n" % cs.timer_overhead_ns.median())

A("## B. Fixed-buffer mode\n")
A(bud.round(1).to_markdown(index=False))
A("\nSources: `results/raw/%s/budget.csv`, `benchmarks/budget_main.cpp`. The baselines cannot run from a fixed buffer; the right-hand columns compare STRATA's buffer with their peak heap.\n" % run)

A("## Ablations and options (compiler traces)\n")
A("| Variant | Effect, measured |\n|---|---|")
A("| Name packing (`strata` vs `strata_raw`) | minimum buffer %s%% smaller; replay time between %.1f%% slower and %.1f%% faster with packing (slower on %d of %d traces) |"
  % (rng(bud["packing saves %"]), -pack_time.min(), pack_time.max(), int((pack_time < 0).sum()), len(pack_time)))
A("| Sparse index (`strata_sparse`, load <= 1/2) | replay time %s%% lower (median %.1f%%); minimum buffer %s%% larger |" % (rng(sparse_gain), sparse_gain.median(), rng(sparse_mem)))
A("| No shrinking (`strata_noshrink`) | on `big_scope_exit` %.1f ns/op against %.1f with shrinking; on compiler traces within noise |" % (big["strata_noshrink"], big["strata"]))
A("")

A("## C. Synthetic stress traces\n")
A(sovn.round(1).to_markdown(index=False))
A("\nNotes:\n")
A("* `deep_shadow_400`: METIS-X refused %d of %d declarations and gave %d wrong lookup results (audit item D1). No other table failed." % (ds.refused_declares, ds.declares, ds.wrong_lookups))
A("* `big_scope_exit` (a 10 000-declaration scope entered 20 times): STRATA %.1f ns/op, METIS-X %.1f, STRATA without shrinking %.1f."
  % (big["strata"], big["metis_x"], big["strata_noshrink"]))
worse = sovn[sovn["replay red. %"] < 0]
A("* STRATA is slower than METIS-X on: %s." % (", ".join("%s (%.1f%%%s)" % (r["trace"], r["replay red. %"], ", intervals overlap" if r["intervals overlap"] == "yes" else "") for _, r in worse.iterrows()) or "no synthetic trace"))
A("* `long_ids`: with 40-80 byte names the memory advantage over METIS-X shrinks to %.1f%%: names dominate and both store them once at the peak." % sovn[sovn.trace == "long_ids"]["peak heap red. %"].iloc[0])
A("\nReplay time, ns per operation:\n")
A(piv(srt, "ns_per_op", COLS + ["strata_sparse", "strata_noshrink"]).round(1).rename(columns=NAMES).reset_index().to_markdown(index=False))
A("\nPeak heap, KiB:\n")
A((piv(ss, "peak_bytes", COLS) / 1024).round(1).rename(columns=NAMES).reset_index().to_markdown(index=False))
A("")

A("## D. Worst case: all keys in one probe cluster\n")
A(wc.to_markdown(index=False))
A("\nWith the hash defeated, a lookup scans the cluster: cost grows linearly with the number of names. STRATA has no defence against this (see `LIMITATIONS.md`).\n")

A("## E. Regex-extracted traces of the earlier work (supplemental)\n")
A("These four traces come from a lexical heuristic, not a compiler. They are shown only for continuity with the METIS-X manuscript.\n")
A(lovn.round(1).to_markdown(index=False))
A("\nThe METIS-X manuscript reported, for its own harness, peak heap of 25.1 MB (Zephyr) and 35.2 MB (ESP-IDF) for METIS-X; those figures "
  "included about 20 MB of harness data (audit item D11). Here METIS-X's own peak is %.1f MB and %.1f MB."
  % (ls[(ls.trace == "Zephyr") & (ls.impl == "metis_x")].peak_bytes.iloc[0] / 1e6, ls[(ls.trace == "ESP-IDF") & (ls.impl == "metis_x")].peak_bytes.iloc[0] / 1e6))
PREV = "20261011-161306-final"
if run != PREV and os.path.isdir(os.path.join("results", "raw", PREV)):
    A("\n## STRATA version 1 against version 2\n")
    A("Version 1 is the table as first reported (run `%s`, commit `3aee381`). Version 2 (this run) changes three things: "
      "the undo entry of a first declaration stores its index slot, so scope exit empties the slot directly instead of re-hashing the name; "
      "the buffer is given back only after 64 consecutive scope exits at low occupancy; and the hash is computed in the packing loop. "
      "The two versions were measured in different runs, so differences of a few percent are within run-to-run variation.\n" % PREV)
    p_cs = pd.read_csv(os.path.join("results", "raw", PREV, "compiler_summary.csv"))
    p_rt = pd.read_csv(os.path.join("results", "summary", PREV, "compiler_replay_time.csv"))
    p_bud = pd.read_csv(os.path.join("results", "summary", PREV, "budget_min_buffer.csv")).set_index("trace")
    rows = []
    for tr in traces:
        a = p_cs[(p_cs.trace == tr) & (p_cs.impl == "strata")].iloc[0]
        b = cs[(cs.trace == tr) & (cs.impl == "strata")].iloc[0]
        ta = p_rt[(p_rt.trace == tr) & (p_rt.impl == "strata")].ns_per_op.iloc[0]
        tb = rt[(rt.trace == tr) & (rt.impl == "strata")].ns_per_op.iloc[0]
        rows.append({"trace": tr, "replay ns/op v1": ta, "v2": tb, "red. %": (ta - tb) / ta * 100,
                     "exit p95 v1": a.exit_p95_ns, "exit p95 v2": b.exit_p95_ns, "exit red. %": (a.exit_p95_ns - b.exit_p95_ns) / a.exit_p95_ns * 100,
                     "lookup p95 v1": a.lookup_p95_ns, "lookup p95 v2": b.lookup_p95_ns,
                     "declare p95 v1": a.declare_p95_ns, "declare p95 v2": b.declare_p95_ns,
                     "peak heap KiB v1": a.peak_bytes / 1024, "peak heap KiB v2": b.peak_bytes / 1024,
                     "min buffer KiB v1": p_bud.loc[tr, "min buffer KiB (packed)"],
                     "min buffer KiB v2": bud.set_index("trace").loc[tr, "min buffer KiB (packed)"]})
    v12 = pd.DataFrame(rows)
    v12.to_csv(os.path.join(S, "strata_v1_vs_v2.csv"), index=False)
    A(v12.round(1).to_markdown(index=False))
    p_srt = pd.read_csv(os.path.join("results", "summary", PREV, "synthetic_replay_time.csv"))
    pb = p_srt[p_srt.trace == "big_scope_exit"].set_index("impl").ns_per_op
    A("\n`big_scope_exit`: STRATA %.1f ns/op in version 1, %.1f in version 2 (METIS-X: %.1f and %.1f in the two runs).\n"
      % (pb["strata"], big["strata"], pb["metis_x"], big["metis_x"]))
A("\n## Run-to-run variation\n")
R1, R2 = "20261011-160113-full", "20261011-161306-final"
if os.path.isdir(os.path.join("results", "raw", R1)) and os.path.isdir(os.path.join("results", "raw", R2)):
    def both(name):
        return pd.concat([pd.read_csv(os.path.join("results", "raw", name, t + "_summary.csv")) for t in ("compiler", "synthetic", "legacy")])
    m = both(R1).merge(both(R2), on=["trace", "impl"], suffixes=("_1", "_2"))
    same_mem = int((abs(m.peak_bytes_1 - m.peak_bytes_2) <= 64).sum())
    dt = (abs(m.replay_ns_median_1 - m.replay_ns_median_2) / m.replay_ns_median_1 * 100)
    lh = lambda r: -pd.read_csv(os.path.join("results", "summary", r, "synthetic_old_vs_new.csv")).set_index("trace").loc["lookup_heavy", "replay red. %"]
    A("`results/raw/` holds two complete runs of the same version-1 table code (`%s` and `%s`). "
      "Of the %d table/trace pairs present in both, %d have the same peak heap to within 64 bytes. "
      "Their median replay times differ by a median of %.1f%% and by up to %.0f%%. "
      "For example, version 1 was %.1f%% slower than METIS-X on `lookup_heavy` in the first of them and %.1f%% slower in the second. "
      "Timing statements in this document should be read with that variation in mind; memory and correctness results do not vary."
      % (R1, R2, len(m), same_mem, dt.median(), dt.max(), lh(R1), lh(R2)))
with open("docs/RESULTS.md", "w", newline="\n") as f:
    f.write("\n".join(md) + "\n")

