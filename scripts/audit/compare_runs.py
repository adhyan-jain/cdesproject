#!/usr/bin/env python3
"""Compare a new benchmark run with a stored one (standard library only).

    python3 scripts/audit/compare_runs.py results/raw/<stored> results/raw/<new> > report.md

Deterministic columns (correctness counters, peak heap, bytes used inside the buffer,
minimum fixed buffer) must be identical for tables whose code did not change. Timing is
compared through paired per-round ratios with a bootstrap interval, as in the stored
analysis; raw medians of the two runs are shown side by side to expose machine drift.
"""
import csv
import random
import statistics
import sys

OLD, NEW = sys.argv[1], sys.argv[2]
TRACES = ["cjson", "littlefs", "zlib", "lua", "freertos", "mbedtls", "tinycc", "sqlite"]
DETERMINISTIC = ["ops", "declares", "lookups", "distinct_names", "peak_live_decls", "max_depth", "wrong_lookups",
                 "wrong_declares", "refused_declares", "peak_bytes", "allocs", "table_used_peak_bytes"]


def summary(run):
    with open(f"{run}/compiler_summary.csv") as fh:
        return {(r["trace"], r["impl"]): r for r in csv.DictReader(fh)}


def replays(run):
    out = {}
    with open(f"{run}/compiler_replays.csv") as fh:
        for r in csv.DictReader(fh):
            out.setdefault((r["trace"], r["impl"]), []).append(float(r["replay_ns"]))
    return out


def paired(a, b, rng):
    """Median of per-round a/b - 1 in percent, with a 95% bootstrap interval."""
    n = min(len(a), len(b))
    ratios = [a[i] / b[i] for i in range(n)]
    point = statistics.median(ratios)
    boots = sorted(statistics.median(rng.choices(ratios, k=n)) for _ in range(2000))
    return (point - 1) * 100, (boots[49] - 1) * 100, (boots[1949] - 1) * 100


def verdict(lo, hi):
    return "faster" if hi < 0 else "slower" if lo > 0 else "not established"


def main():
    rng = random.Random(20261013)
    so, sn, ro, rn = summary(OLD), summary(NEW), replays(OLD), replays(NEW)
    print(f"# Reproduction check: `{NEW}` against `{OLD}`\n")
    print("Generated by `scripts/audit/compare_runs.py`. Do not edit numbers by hand.\n")

    # 1. deterministic results
    mismatches, compared = [], 0
    for key in sorted(so):
        if key not in sn or key[0] not in TRACES:
            continue
        for col in DETERMINISTIC:
            compared += 1
            if so[key][col] != sn[key][col]:
                mismatches.append((key, col, so[key][col], sn[key][col]))
    print("## 1. Deterministic results\n")
    print(f"{compared} values compared ({len(DETERMINISTIC)} columns x table/trace pairs present in both runs); "
          f"{len(mismatches)} differ.\n")
    if mismatches:
        print("| Trace | Table | Column | Stored | New |\n|---|---|---|---|---|")
        for (t, i), col, a, b in mismatches:
            print(f"| {t} | {i} | {col} | {a} | {b} |")
        print()
    wrong = [(k, r["wrong_lookups"], r["wrong_declares"], r["refused_declares"]) for k, r in sorted(sn.items())
             if int(r["wrong_lookups"]) or int(r["wrong_declares"]) or int(r["refused_declares"])]
    print(f"Table/trace pairs in the new run: {len(sn)}. Pairs with a wrong lookup, a wrong declaration result or a "
          f"refused declaration: {len(wrong)}{'' if not wrong else ' ' + str(wrong)}.\n")

    try:
        def budget(run):
            with open(f"{run}/budget.csv") as fh:
                return {(r["trace"], r["names"]): r["min_buffer_bytes"] for r in csv.DictReader(fh) if r["budget_factor"] == "1.00"}
        bo, bn = budget(OLD), budget(NEW)
        same = sum(1 for k in bn if bo.get(k) == bn[k])
        print(f"Minimum fixed buffer (budget.csv): {len(bn)} values in the new run, {same} identical to the stored run.\n")
        diff = {k: (bo.get(k), bn[k]) for k in bn if bo.get(k) != bn[k]}
        if diff:
            print(f"Differences: {diff}\n")
    except (OSError, KeyError) as e:
        print(f"Minimum fixed buffer: not compared ({e}).\n")

    # 2. timing claims, old and new
    def claim(title, a, b):
        print(f"## {title}\n")
        print("Negative = the first table is faster. Paired per-round ratios, median, 95% bootstrap interval.\n")
        print("| Trace | Stored run | | New run | |\n|---|---|---|---|---|")
        agree = 0
        rows = 0
        for t in TRACES:
            cells = []
            verdicts = []
            for r in (ro, rn):
                if (t, a) in r and (t, b) in r:
                    p, lo, hi = paired(r[(t, a)], r[(t, b)], rng)
                    cells += [f"{p:+.1f}% [{lo:+.1f}, {hi:+.1f}]", verdict(lo, hi)]
                    verdicts.append(verdict(lo, hi))
                else:
                    cells += ["-", "-"]
            if len(verdicts) == 2:
                rows += 1
                agree += verdicts[0] == verdicts[1]
            print(f"| {t} | " + " | ".join(cells) + " |")
        print(f"\nSame verdict in both runs on {agree} of {rows} traces.\n")

    claim("2. STRATA against METIS-X (replay time)", "strata", "metis_x")
    claim("3. STRATA against the conventional arena table (replay time)", "strata", "arena_chain")
    claim("4. Conventional arena table against METIS-X (replay time)", "arena_chain", "metis_x")

    print("## 5. Keyed hash (HalfSipHash-1-3) against the default hash, new run\n")
    print("| Trace | strata_keyed vs strata | Verdict |\n|---|---|---|")
    for t in TRACES:
        if (t, "strata_keyed") in rn:
            p, lo, hi = paired(rn[(t, "strata_keyed")], rn[(t, "strata")], rng)
            print(f"| {t} | {p:+.1f}% [{lo:+.1f}, {hi:+.1f}] | {verdict(lo, hi)} |")
    print()

    print("## 6. Raw median replay time, stored and new (ms)\n")
    impls = ["strata", "arena_chain", "metis_x", "swiss_interned", "strata_keyed"]
    print("| Trace | " + " | ".join(f"{i} stored | {i} new" for i in impls) + " |")
    print("|---|" + "---|---|" * len(impls))
    drift = []
    for t in TRACES:
        cells = []
        for i in impls:
            a = statistics.median(ro[(t, i)]) / 1e6 if (t, i) in ro else None
            b = statistics.median(rn[(t, i)]) / 1e6 if (t, i) in rn else None
            cells += [f"{a:.3f}" if a else "-", f"{b:.3f}" if b else "-"]
            if a and b:
                drift.append(b / a)
        print(f"| {t} | " + " | ".join(cells) + " |")
    if drift:
        print(f"\nNew/stored ratio of the medians over these {len(drift)} pairs: median {statistics.median(drift):.3f}, "
              f"min {min(drift):.3f}, max {max(drift):.3f}.\n")

    print("## 7. Per-operation latency of STRATA against METIS-X, p95 (ns), new run\n")
    print("| Trace | lookup | declare | scope exit |\n|---|---|---|---|")
    for t in TRACES:
        a, b = sn.get((t, "strata")), sn.get((t, "metis_x"))
        if a and b:
            def cell(col):
                x, y = float(a[col]), float(b[col])
                return f"{x:.0f} vs {y:.0f} ({(x / y - 1) * 100:+.0f}%)" if y else f"{x:.0f} vs {y:.0f}"
            print(f"| {t} | {cell('lookup_p95_ns')} | {cell('declare_p95_ns')} | {cell('exit_p95_ns')} |")
    print()


if __name__ == "__main__":
    main()
