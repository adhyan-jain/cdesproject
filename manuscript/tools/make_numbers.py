#!/usr/bin/env python3
"""Generate every number, table and data file the manuscript uses.

    python manuscript/tools/make_numbers.py [results/raw/<run>]      (repository root)

Reads the raw CSV files of one full run (default: the newest results/raw/*-paper), the two
runs that bracket the rebuild change, and results/hardening/. Writes

    paper/generated_numbers.tex    scalar macros (\\newcommand)
    paper/tables/tab_*.tex         tabular bodies
    manuscript/figures/source/data_*.csv         the series plotted by make_plots.py

No number in main.tex is typed by hand; change the data, rerun this, recompile.
"""
import csv
import glob
import math
import os
import random
import statistics
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RUN = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob(os.path.join(ROOT, "results/raw/*-paper")))[-1]
BEFORE = os.path.join(ROOT, "results/raw/20261013-120345-audit")    # before the rebuild change
OUT = os.path.join(ROOT, "paper")    # canonical; manuscript/ieee_access keeps its own copy of the generated files
os.makedirs(os.path.join(OUT, "tables"), exist_ok=True)
DATA = os.path.join(ROOT, "manuscript/figures/source")
TRACES = ["cjson", "littlefs", "zlib", "lua", "freertos", "mbedtls", "tinycc", "sqlite"]
LABEL = {"cjson": "cJSON", "littlefs": "littlefs", "zlib": "zlib", "lua": "Lua", "freertos": "FreeRTOS",
         "mbedtls": "Mbed TLS", "tinycc": "TinyCC", "sqlite": "SQLite"}
rng = random.Random(20261013)
macros = {}


def rows(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def summary(run, name="compiler"):
    return {(r["trace"], r["impl"]): r for r in rows(os.path.join(run, name + "_summary.csv"))}


def replays(run, name="compiler"):
    out = {}
    for r in rows(os.path.join(run, name + "_replays.csv")):
        out.setdefault((r["trace"], r["impl"]), []).append(float(r["replay_ns"]))
    return out


def paired(a, b):
    """Median of per-round a/b - 1 in percent, with a 95% bootstrap interval."""
    n = min(len(a), len(b))
    ratios = [a[i] / b[i] for i in range(n)]
    boots = sorted(statistics.median(rng.choices(ratios, k=n)) for _ in range(2000))
    return (statistics.median(ratios) - 1) * 100, (boots[49] - 1) * 100, (boots[1949] - 1) * 100


def verdict(lo, hi):
    return "faster" if hi < 0 else "slower" if lo > 0 else "n.e."


def pct(x, signed=True):
    s = f"{x:+.1f}" if signed else f"{x:.1f}"
    return s.replace("-", "$-$").replace("+", "$+$")


def num(n):
    """Integer with thin-space thousands separators."""
    return f"{int(n):,}".replace(",", "\\,")


def sci(x):
    if x == 0:
        return "0"
    e = int(math.floor(math.log10(x)))
    m = x / 10 ** e
    return f"${m:.1f}\\!\\times\\!10^{{{e}}}$"


def write(name, lines):
    with open(os.path.join(OUT, "tables", name), "w", encoding="utf-8", newline="\n") as fh:
        # The closing rule is part of the file: LaTeX's \input is not expandable, so an
        # \hline written after it in the manuscript would be "misplaced".
        fh.write("% generated by manuscript/tools/make_numbers.py; do not edit\n" + "\n".join(lines) + "\n\\hline\n")


def data(name, header, body):
    with open(os.path.join(DATA, name), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(",".join(header) + "\n")
        for r in body:
            fh.write(",".join(str(x) for x in r) + "\n")


S, R = summary(RUN), replays(RUN)
B = {(r["trace"], r["names"], r["budget_factor"]): r for r in rows(os.path.join(RUN, "budget.csv"))}
macros["RunName"] = os.path.basename(RUN).replace("_", "\\_")

# ---- correctness ------------------------------------------------------------------------
impls = sorted({k[1] for k in S})
bad = [k for k, r in S.items() if int(r["wrong_lookups"]) or int(r["wrong_declares"]) or int(r["refused_declares"])]
assert not bad, bad
macros["NTables"] = str(len(impls))
macros["NPairsAll"] = str(len(S))
macros["NPairs"] = str(sum(1 for k in S if k[0] in TRACES))
macros["NTracesAll"] = str(len({k[0] for k in S}))

# ---- workloads --------------------------------------------------------------------------
lines = []
tot_ops = tot_decl = 0
for t in TRACES:
    r = S[(t, "strata")]
    tot_ops += int(r["ops"])
    tot_decl += int(r["declares"])
    lines.append(f"{LABEL[t]} & {r['units']} & {num(r['ops'])} & {num(r['declares'])} & {num(r['lookups'])} & "
                 f"{num(r['distinct_names'])} & {num(r['peak_live_decls'])} & {r['max_depth']} \\\\")
write("tab_workloads.tex", lines)
macros["TotalEvents"] = num(tot_ops)
macros["TotalDecls"] = num(tot_decl)

# ---- memory -----------------------------------------------------------------------------
lines, save, bpd, heap_m, allocs, pack_save = [], [], [], [], [], []
mem_data = []
for t in TRACES:
    st = int(B[(t, "packed", "1.00")]["min_buffer_bytes"])
    ar = int(B[(t, "arena_chain", "1.00")]["min_buffer_bytes"])
    raw = int(B[(t, "raw", "1.00")]["min_buffer_bytes"])
    sp = int(B[(t, "packed_sparse", "1.00")]["min_buffer_bytes"])
    live = int(S[(t, "strata")]["peak_live_decls"])
    hp = {i: int(S[(t, i)]["peak_bytes"]) for i in impls}
    save.append((1 - st / ar) * 100)
    bpd.append(st / live)
    heap_m.append((1 - hp["strata"] / hp["metis_x"]) * 100)
    allocs.append((1 - int(S[(t, "strata")]["allocs"]) / int(S[(t, "metis_x")]["allocs"])) * 100)
    pack_save.append((1 - st / raw) * 100)
    lines.append(f"{LABEL[t]} & {st / 1024:.1f} & {ar / 1024:.1f} & {save[-1]:.1f} & {bpd[-1]:.1f} & "
                 f"{hp['strata'] / 1024:.1f} & {hp['arena_chain'] / 1024:.1f} & {hp['metis_x'] / 1024:.1f} & "
                 f"{hp['scope_map_stack'] / 1024:.1f} & {hp['std_undo_log'] / 1024:.1f} & {hp['swiss_interned'] / 1024:.1f} \\\\")
    mem_data.append((t, LABEL[t], st, ar, raw, sp))
write("tab_memory.tex", lines)
data("data_minbuffer.csv", ["trace", "label", "strata", "arena_chain", "strata_raw", "strata_sparse"], mem_data)
same = sum(1 for t in TRACES if abs(int(S[(t, "strata")]["peak_bytes"]) / int(S[(t, "arena_chain")]["peak_bytes"]) - 1) < 0.01)
lower = sum(1 for t in TRACES if int(S[(t, "strata")]["peak_bytes"]) / int(S[(t, "arena_chain")]["peak_bytes"]) <= 0.99)
assert same + lower == len(TRACES)
macros["HeapSameArena"] = str(same)
macros["HeapLowerArena"] = str(lower)
mins = [int(B[(t, "packed", "1.00")]["min_buffer_bytes"]) / 1024 for t in TRACES]
macros.update(MinBufLo=f"{min(mins):.1f}", MinBufHi=f"{max(mins):.1f}", SaveLo=f"{min(save):.1f}", SaveHi=f"{max(save):.1f}",
              BytesLo=f"{min(bpd):.0f}", BytesHi=f"{max(bpd):.0f}", HeapMetisLo=f"{min(heap_m):.0f}", HeapMetisHi=f"{max(heap_m):.0f}",
              HeapMetisMed=f"{statistics.median(heap_m):.0f}", AllocLo=f"{min(allocs):.1f}", AllocHi=f"{max(allocs):.1f}",
              PackSaveLo=f"{min(pack_save):.1f}", PackSaveHi=f"{max(pack_save):.1f}")

# ---- replay time ------------------------------------------------------------------------
lines, time_data = [], []
cmp_ = {"sa": ("strata", "arena_chain"), "sm": ("strata", "metis_x"), "am": ("arena_chain", "metis_x"), "ks": ("strata_keyed", "strata")}
res = {k: {} for k in cmp_}
for t in TRACES:
    cells = [LABEL[t]]
    for k, (a, b) in cmp_.items():
        p, lo, hi = paired(R[(t, a)], R[(t, b)])
        res[k][t] = (p, lo, hi)
        cells.append(f"{pct(p)} [{pct(lo)}, {pct(hi)}]")
        if k != "ks":
            cells.append(verdict(lo, hi))
    lines.append(" & ".join(cells) + " \\\\")
write("tab_time.tex", lines)
# spread of the raw replay times: interquartile range over median, per table and trace
iqr = []
for (t, i), v in R.items():
    if t in TRACES:
        q = statistics.quantiles(v, n=4)
        iqr.append((q[2] - q[0]) / statistics.median(v) * 100)
macros["IqrMedian"] = f"{statistics.median(iqr):.0f}"
# one compact table for the four-page version: memory and time per trace
lines = []
for t in TRACES:
    st_ = int(B[(t, "packed", "1.00")]["min_buffer_bytes"])
    ar_ = int(B[(t, "arena_chain", "1.00")]["min_buffer_bytes"])
    p, lo, hi = res["sa"][t]
    pm, lom, him = res["sm"][t]
    lines.append(f"{LABEL[t]} & {st_ / 1024:.1f} & {ar_ / 1024:.1f} & {(1 - st_ / ar_) * 100:.1f} & "
                 f"{pct(p)} [{pct(lo)}, {pct(hi)}] & {pct(pm)} [{pct(lom)}, {pct(him)}] \\\\")
write("tab_short.tex", lines)


def counts(k):
    v = [verdict(lo, hi) for _, lo, hi in res[k].values()]
    return v.count("faster"), v.count("slower"), v.count("n.e.")


f, s, n = counts("sa")
pts = [p for p, _, _ in res["sa"].values()]
macros.update(ArenaFaster=str(f), ArenaSlower=str(s), ArenaNE=str(n), ArenaLo=pct(min(pts)), ArenaHi=pct(max(pts)),
              ArenaAbsMax=f"{max(abs(x) for x in pts):.1f}")
f, s, n = counts("sm")
pts = [-p for p, _, _ in res["sm"].values()]
macros.update(MetisFaster=str(f), MetisSlower=str(s), MetisNE=str(n), MetisLo=f"{min(pts):.1f}", MetisHi=f"{max(pts):.1f}")
f, s, n = counts("am")
pts = [-p for p, _, _ in res["am"].values()]
macros.update(AMFaster=str(f), AMLo=f"{min(pts):.1f}", AMHi=f"{max(pts):.1f}")
pts = [p for p, _, _ in res["ks"].values()]
macros.update(KeyedLo=f"{min(pts):.1f}", KeyedHi=f"{max(pts):.1f}")

# ---- before and after the rebuild change --------------------------------------------------
Rb = replays(BEFORE)
lines, before_pts = [], []
for t in TRACES:
    p0, lo0, hi0 = paired(Rb[(t, "strata")], Rb[(t, "arena_chain")])
    p1, lo1, hi1 = res["sa"][t]
    before_pts.append(p0)
    lines.append(f"{LABEL[t]} & {pct(p0)} [{pct(lo0)}, {pct(hi0)}] & {pct(p1)} [{pct(lo1)}, {pct(hi1)}] \\\\")
    time_data.append((t, LABEL[t], f"{p0:.3f}", f"{lo0:.3f}", f"{hi0:.3f}", f"{p1:.3f}", f"{lo1:.3f}", f"{hi1:.3f}"))
write("tab_beforeafter.tex", lines)
data("data_time.csv", ["trace", "label", "before", "before_lo", "before_hi", "after", "after_lo", "after_hi"], time_data)
macros.update(BeforeLo=f"{min(before_pts):.1f}", BeforeHi=f"{max(before_pts):.1f}")
Sb = summary(BEFORE)
det = ["wrong_lookups", "wrong_declares", "refused_declares", "peak_bytes", "allocs", "table_used_peak_bytes"]
macros["DetCompared"] = str(sum(1 for k in Sb if k in S for _ in det))
# heap peaks of unchanged tables move by allocator rounding; bytes used inside the buffer must not
moved = [k for k in Sb if k in S and k[1].startswith("strata") and Sb[k]["table_used_peak_bytes"] != S[k]["table_used_peak_bytes"]]
assert not moved, moved
Bb = {(r["trace"], r["names"], r["budget_factor"]): r["min_buffer_bytes"] for r in rows(os.path.join(BEFORE, "budget.csv"))}
assert all(Bb[k] == B[k]["min_buffer_bytes"] for k in Bb if k[2] == "1.00"), "minimum buffers changed"

# ---- per-operation latency ----------------------------------------------------------------
lines, dl, xl, ll = [], [], [], []
for t in TRACES:
    a, c, m = S[(t, "strata")], S[(t, "arena_chain")], S[(t, "metis_x")]
    cells = [LABEL[t]]
    for col in ("lookup_p95_ns", "declare_p95_ns", "exit_p95_ns"):
        cells += [f"{float(a[col]):.0f}", f"{float(c[col]):.0f}", f"{float(m[col]):.0f}"]
    dl.append((1 - float(a["declare_p95_ns"]) / float(m["declare_p95_ns"])) * 100)
    xl.append((1 - float(a["exit_p95_ns"]) / float(m["exit_p95_ns"])) * 100)
    ll.append((float(a["lookup_p95_ns"]) / float(m["lookup_p95_ns"]) - 1) * 100)
    lines.append(" & ".join(cells) + " \\\\")
write("tab_latency.tex", lines)
macros.update(DeclLo=f"{min(dl):.0f}", DeclHi=f"{max(dl):.0f}", ExitLo=f"{min(xl):.0f}", ExitHi=f"{max(xl):.0f}",
              LookLo=pct(min(ll)).replace(".0", ""), LookHi=pct(max(ll)).replace(".0", ""))

# ---- ablations ------------------------------------------------------------------------------
lines = []
abl = {"raw": [], "sparse": [], "noshrink": []}
for t in TRACES:
    st = int(B[(t, "packed", "1.00")]["min_buffer_bytes"])
    raw = int(B[(t, "raw", "1.00")]["min_buffer_bytes"])
    sp = int(B[(t, "packed_sparse", "1.00")]["min_buffer_bytes"])
    pr = paired(R[(t, "strata_raw")], R[(t, "strata")])
    ps = paired(R[(t, "strata_sparse")], R[(t, "strata")])
    pn = paired(R[(t, "strata_noshrink")], R[(t, "strata")])
    abl["raw"].append(pr); abl["sparse"].append(ps); abl["noshrink"].append(pn)
    lines.append(f"{LABEL[t]} & {pct((raw / st - 1) * 100)} & {pct(pr[0])} ({verdict(pr[1], pr[2])}) & "
                 f"{pct((sp / st - 1) * 100)} & {pct(ps[0])} ({verdict(ps[1], ps[2])}) & {pct(pn[0])} ({verdict(pn[1], pn[2])}) \\\\")
write("tab_ablation.tex", lines)
for k, name in (("raw", "Raw"), ("sparse", "Sparse"), ("noshrink", "NoShrink")):
    v = [verdict(lo, hi) for _, lo, hi in abl[k]]
    macros[name + "Faster"] = str(v.count("faster"))
    macros[name + "Slower"] = str(v.count("slower"))
    macros[name + "Lo"] = pct(min(p for p, _, _ in abl[k]))
    macros[name + "Hi"] = pct(max(p for p, _, _ in abl[k]))
sp_cost = [(int(B[(t, "packed_sparse", "1.00")]["min_buffer_bytes"]) / int(B[(t, "packed", "1.00")]["min_buffer_bytes"]) - 1) * 100 for t in TRACES]
macros.update(SparseBufLo=f"{min(sp_cost):.0f}", SparseBufHi=f"{max(sp_cost):.0f}")

# ---- synthetic traces -----------------------------------------------------------------------
if os.path.exists(os.path.join(RUN, "synthetic_summary.csv")):
    SS, SR = summary(RUN, "synthetic"), replays(RUN, "synthetic")
    names = sorted({k[0] for k in SS})
    lines = []
    wins = 0
    for t in names:
        r = SS[(t, "strata")]
        pa = paired(SR[(t, "strata")], SR[(t, "arena_chain")])
        pm = paired(SR[(t, "strata")], SR[(t, "metis_x")])
        mx = SS[(t, "metis_x")]
        wins += verdict(pa[1], pa[2]) == "faster"
        note = f"{num(mx['refused_declares'])} refused" if int(mx["refused_declares"]) else "agrees"
        lines.append(f"\\texttt{{{t.replace('_', chr(92) + '_')}}} & {num(r['declares'])} & {r['max_depth']} & "
                     f"{pct(pa[0])} ({verdict(pa[1], pa[2])}) & {pct(pm[0])} ({verdict(pm[1], pm[2])}) & {note} \\\\")
    write("tab_synthetic.tex", lines)
    macros["SynCount"] = str(len(names))
    macros["SynFasterArena"] = str(wins)
    macros["SynSlowerArena"] = str(sum(1 for t in names if verdict(*paired(SR[(t, "strata")], SR[(t, "arena_chain")])[1:]) == "slower"))
    badsyn = [(k, r["refused_declares"]) for k, r in SS.items() if int(r["wrong_lookups"]) or int(r["refused_declares"])]
    macros["SynBadPairs"] = str(len(badsyn))
    macros["MetisRefused"] = num(SS[("deep_shadow_400", "metis_x")]["refused_declares"]) if ("deep_shadow_400", "metis_x") in SS else "?"
    macros["MetisRefusedOf"] = num(SS[("deep_shadow_400", "metis_x")]["declares"]) if ("deep_shadow_400", "metis_x") in SS else "?"

# ---- per-unit fit and sweep -----------------------------------------------------------------
if os.path.exists(os.path.join(RUN, "units.csv")):
    U = [r for r in rows(os.path.join(RUN, "units.csv")) if not r["trace"].startswith("chibicc_")]
    macros["UnitsTotal"] = str(len(U))
    lines = []
    for kib in (8, 16, 32, 64, 128):
        b = kib * 1024
        both = sum(1 for r in U if int(r["arena_chain_min_bytes"]) <= b)
        only = sum(1 for r in U if int(r["strata_min_bytes"]) <= b < int(r["arena_chain_min_bytes"]))
        neither = sum(1 for r in U if int(r["strata_min_bytes"]) > b)
        lines.append(f"{kib} & {both} & {only} & {neither} \\\\")
        if kib == 16:
            macros["UnitOnlySixteen"] = str(only)
    write("tab_unitfit.tex", lines)
if os.path.exists(os.path.join(RUN, "sweep_minbuf.csv")):
    SW = {r["trace"]: r for r in rows(os.path.join(RUN, "sweep_minbuf.csv"))}
    SWR = replays(RUN, "sweep")
    lines, best = [], 0.0
    for sigma in ("10", "15", "20", "40", "80"):
        cells = [f"{int(sigma) / 10:.1f}"]
        for L in ("06", "12", "24"):
            t = f"s{sigma}_L{L}"
            sv = (1 - int(SW[t]["strata_min_bytes"]) / int(SW[t]["arena_chain_min_bytes"])) * 100
            best = max(best, sv)
            p = paired(SWR[(t, "strata")], SWR[(t, "arena_chain")])
            cells.append(f"{sv:.0f} & {pct(p[0])} ({verdict(p[1], p[2])})")
        lines.append(" & ".join(cells) + " \\\\")
    write("tab_sweep.tex", lines)
    macros["SweepBestSave"] = f"{best:.0f}"

# ---- hash flooding --------------------------------------------------------------------------
F = {(r["input"], r["config"], int(r["n"])): r for r in rows(os.path.join(ROOT, "results/hardening/flood.csv"))}
ns = sorted({k[2] for k in F})
lines, flood_data = [], []
for n in ns:
    o, e = F[("ordinary", "default", n)], F[("colliding", "default", n)]
    od, ed = float(o["declare_ns_median"]) / 1e6, float(e["declare_ns_median"]) / 1e6
    lines.append(f"{num(n)} & {od:.2f} & {ed:.2f} & {ed / od:.0f} & {float(e['lookup_ns_median']) / 1e6:.2f} \\\\")
    row = [n]
    for inp in ("ordinary", "colliding"):
        for c in ("default", "keyed", "bounded", "bounded_keyed"):
            row.append(f"{float(F[(inp, c, n)]['declare_ns_median']) / 1e6:.4f}")
    flood_data.append(row)
write("tab_flood_scale.tex", lines)
data("data_flood.csv", ["n"] + [f"{i}_{c}" for i in ("ordinary", "colliding") for c in ("default", "keyed", "bounded", "bounded_keyed")], flood_data)
top = ns[-1]
lines = []
names_cfg = {"default": "Default", "keyed": "Keyed hash", "bounded": "Limit 64", "bounded_keyed": "Limit 64, keyed"}
for c in ("default", "keyed", "bounded", "bounded_keyed"):
    o, e = F[("ordinary", c, top)], F[("colliding", c, top)]
    od, ed = float(o["declare_ns_median"]) / 1e6, float(e["declare_ns_median"]) / 1e6
    lines.append(f"{names_cfg[c]} & {od:.2f} & {ed:.2f} & {ed / od:.1f} & {num(e['refused'])} & {num(e['longest_probe'])} \\\\")
write("tab_flood_config.tex", lines)
o, e = F[("ordinary", "default", top)], F[("colliding", "default", top)]
a, b = float(F[("colliding", "default", ns[0])]["declare_ns_median"]), float(e["declare_ns_median"])
macros.update(FloodN=num(top), FloodOrd=f"{float(o['declare_ns_median']) / 1e6:.1f}", FloodCol=f"{float(e['declare_ns_median']) / 1e6:.0f}",
              FloodRatio=f"{float(e['declare_ns_median']) / float(o['declare_ns_median']):.0f}",
              FloodLookCol=f"{float(e['lookup_ns_median']) / 1e6:.0f}", FloodExp=f"{math.log(b / a) / math.log(top / ns[0]):.2f}",
              FloodKeyedRatio=f"{float(F[('colliding', 'keyed', top)]['declare_ns_median']) / float(F[('ordinary', 'keyed', top)]['declare_ns_median']):.1f}",
              FloodBoundedRefused=num(F[("colliding", "bounded", top)]["refused"]),
              FloodBoundedRatio=f"{float(F[('colliding', 'bounded', top)]['declare_ns_median']) / float(F[('ordinary', 'bounded', top)]['declare_ns_median']):.1f}")
assert all(r["correct"] == "1" for r in F.values())

# ---- probe lengths against the bound ----------------------------------------------------------
P = rows(os.path.join(ROOT, "results/hardening/probes.csv"))
limits = ("32", "64", "128", "256", "512")
viol = sum(1 for r in P for L in ("8", "16") + limits if float(r["measured_gt_" + L]) > float(r["bound_gt_" + L]))
assert viol == 0
macros["ProbeConfigs"] = str(len(P))
macros["ProbeCells"] = str(len(P) * 7)
macros["ProbeSamples"] = num(P[0]["samples"])
macros["ProbeTotal"] = num(sum(int(r["samples"]) for r in P))
