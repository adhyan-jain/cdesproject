#!/bin/bash
# SHA-256 checksums of every trace file used by the paper.
#   tools/review/trace_checksums.sh            write docs/trace_checksums.sha256 (and the _uncompressed list)
#   tools/review/trace_checksums.sh --check    verify the stored lists against workloads/traces/
# Lists: the compressed files as shipped (verify with `sha256sum -c`), and the decompressed
# trace text (what the benchmarks actually read; independent of gzip settings).
set -eu
cd "$(dirname "$0")/../.."
T=workloads/traces
A=docs/trace_checksums.sha256
B=docs/trace_checksums_uncompressed.sha256
if [ "${1:-}" = "--check" ]; then
  sha256sum -c "$A"
  while read -r h name; do
    got=$(gunzip -c "$T/$name" | sha256sum | cut -d' ' -f1)
    [ "$got" = "$h" ] && echo "$name (decompressed): OK" || { echo "$name (decompressed): FAILED"; exit 1; }
  done < <(grep -v '^#' "$B")
  exit 0
fi
{
  echo "# SHA-256 of the files in workloads/traces/ (compressed, as shipped). Verify: sha256sum -c docs/trace_checksums.sha256"
  echo "# Generated by tools/review/trace_checksums.sh at commit $(git rev-parse HEAD)"
  for f in $(ls $T | LC_ALL=C sort); do sha256sum "$T/$f"; done
} > "$A"
{
  echo "# SHA-256 of the decompressed trace text (gunzip -c FILE | sha256sum). Verify: tools/review/trace_checksums.sh --check"
  echo "# Format: hash  file-name (relative to workloads/traces/)"
  for f in $(ls $T | LC_ALL=C sort | grep '\.trace\.gz$'); do echo "$(gunzip -c "$T/$f" | sha256sum | cut -d' ' -f1)  $f"; done
} > "$B"
echo "wrote $A and $B"
